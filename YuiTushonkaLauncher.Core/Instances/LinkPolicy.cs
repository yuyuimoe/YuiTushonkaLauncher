using YuiTushonkaLauncher.Core.Domain;

namespace YuiTushonkaLauncher.Core.Instances;

/// <summary>What the instance builder does with one entry of the base install.</summary>
public enum LinkAction
{
    /// <summary>Hard link: the file stays shared with the base install.</summary>
    Link,

    /// <summary>Copy: the instance gets a private file (patched binaries, configs, launchers).</summary>
    Copy,

    /// <summary>Do not create this entry; the instance gets it from elsewhere or regenerates it.</summary>
    Skip,

    /// <summary>Create the directory (and nothing inside it).</summary>
    CreateDirectory,
}

/// <summary>
/// The per-path policy that decides what an instance shares with its base install
/// (see <c>docs/plan/01-architecture.md#link-policy</c>).
/// </summary>
/// <remarks>
/// The policy is written in terms of the <em>base</em> path (a split base says <c>gamefiles/…</c> and
/// <c>spt/…</c>, a merged base says the same thing without the wrappers) and answers for the instance, which
/// is always <see cref="InstallShape.Merged" />. Anything not matched explicitly is
/// <see cref="LinkAction.Copy" />: a path that appears in a future SPT release must never be shared by
/// accident.
/// </remarks>
public static class LinkPolicy
{
    /// <summary>Installer scaffolding that belongs to the base, not to an instance.</summary>
    private static readonly string[] BaseOnlyFiles = ["create-spt-instance.sh", "Install_EFT", "installer_log.txt"];

    /// <summary>Top-level entries that belong to the game half, when the base is already merged.</summary>
    private static readonly string[] MergedGameRoots = ["EscapeFromTarkov_Data/", "MonoBleedingEdge/", "NLog/"];

    /// <summary>Top-level files that belong to the game half, when the base is already merged.</summary>
    private static readonly string[] MergedGameFiles = ["EscapeFromTarkov.exe", "UnityPlayer.dll", "Register Game.exe"];

    /// <summary>Top-level entries that belong to the SPT half, when the base is already merged.</summary>
    private static readonly string[] MergedSptRoots = ["BepInEx/", "SPT_Runtime/", "SPT/", "Logs/"];

    /// <summary>Top-level files that belong to the SPT half, when the base is already merged.</summary>
    private static readonly string[] MergedSptFiles = ["winhttp.dll", "doorstop_config.ini", ".doorstop_version", "BepInEx"];

    /// <summary>Decides what to do with a base-install entry given its path relative to the base root.</summary>
    public static LinkAction Decide(string baseRelativePath, bool isDirectory, InstallShape shape)
    {
        var path = Normalize(baseRelativePath);

        if (path.Length == 0)
        {
            return LinkAction.Skip;
        }

        var (part, rest) = Classify(path, shape);

        // The patched binary must never be shared: a patch would rewrite every instance at once.
        if (path.EndsWith(InstancePaths.PatchedAssembly, StringComparison.OrdinalIgnoreCase))
        {
            return LinkAction.Copy;
        }

        // A backup belongs to the instance's own patch state.
        if (path.EndsWith(".spt-bak", StringComparison.OrdinalIgnoreCase))
        {
            return LinkAction.Copy;
        }

        return part switch
        {
            Part.Game => isDirectory ? LinkAction.CreateDirectory : LinkAction.Link,
            Part.Unknown => Unknown(path, isDirectory, shape),
            _ => Spt(rest, isDirectory),
        };
    }

    private static LinkAction Unknown(string path, bool isDirectory, InstallShape shape)
    {
        // Installer scaffolding: it makes instances, it does not belong to one.
        if (!isDirectory && shape == InstallShape.Split && BaseOnlyFiles.Contains(path, StringComparer.OrdinalIgnoreCase))
        {
            return LinkAction.Skip;
        }

        return isDirectory ? LinkAction.CreateDirectory : LinkAction.Copy;
    }

    private static LinkAction Spt(string path, bool isDirectory)
    {
        // BepInEx caches are regenerated by the loader.
        if (IsUnder(path, "BepInEx/cache"))
        {
            return LinkAction.Skip;
        }

        // SPT's own plugins are required for the game to run; user plugins are per instance.
        if (IsUnder(path, "BepInEx/plugins"))
        {
            // A mod archive may ship "BepInEx/plugins" itself, and so may a base: keep the folder, never its loose files.
            if (path.Equals("BepInEx/plugins", StringComparison.OrdinalIgnoreCase))
            {
                return isDirectory ? LinkAction.CreateDirectory : LinkAction.Skip;
            }

            return IsUnder(path, "BepInEx/plugins/spt") ? (isDirectory ? LinkAction.CreateDirectory : LinkAction.Link) : LinkAction.Skip;
        }

        // BepInEx configuration is instance-local.
        if (IsUnder(path, "BepInEx/config"))
        {
            return isDirectory ? LinkAction.CreateDirectory : LinkAction.Copy;
        }

        if (IsUnder(path, "BepInEx/core") || IsUnder(path, "BepInEx/patchers"))
        {
            return isDirectory ? LinkAction.CreateDirectory : LinkAction.Link;
        }

        if (IsUnder(path, "BepInEx"))
        {
            return isDirectory ? LinkAction.CreateDirectory : LinkAction.Copy;
        }

        foreach (var runtime in RuntimeDirectories())
        {
            // user/ holds profiles, logs, mods, caches: always private.
            if (IsUnder(path, $"{runtime}/user"))
            {
                return LinkAction.Skip;
            }

            // The HTTP config holds the port, which is per instance.
            if (IsUnder(path, $"{runtime}/SPT_Data/configs"))
            {
                return isDirectory ? LinkAction.CreateDirectory : LinkAction.Copy;
            }
        }

        return isDirectory ? LinkAction.CreateDirectory : LinkAction.Link;
    }

    private static (Part Part, string Remainder) Classify(string path, InstallShape shape)
    {
        if (shape == InstallShape.Split)
        {
            if (IsUnder(path, "gamefiles"))
            {
                return (Part.Game, path["gamefiles".Length..].TrimStart('/'));
            }

            if (IsUnder(path, "spt"))
            {
                return (Part.Spt, path["spt".Length..].TrimStart('/'));
            }

            return (Part.Unknown, path);
        }

        if (
            MergedGameRoots.Any(root => path.StartsWith(root, StringComparison.OrdinalIgnoreCase))
            || MergedGameFiles.Contains(path, StringComparer.OrdinalIgnoreCase)
        )
        {
            return (Part.Game, path);
        }

        if (
            MergedSptRoots.Any(root => path.StartsWith(root, StringComparison.OrdinalIgnoreCase))
            || MergedSptFiles.Contains(path, StringComparer.OrdinalIgnoreCase)
        )
        {
            return (Part.Spt, path);
        }

        return (Part.Unknown, path);
    }

    private static IEnumerable<string> RuntimeDirectories()
    {
        return ["SPT_Runtime", "SPT"];
    }

    private static string Normalize(string relativePath)
    {
        return relativePath.Replace('\\', '/').Trim('/');
    }

    private static bool IsUnder(string path, string prefix)
    {
        return path.Equals(prefix, StringComparison.OrdinalIgnoreCase) || path.StartsWith(prefix + "/", StringComparison.OrdinalIgnoreCase);
    }

    private enum Part
    {
        Game,
        Spt,
        Unknown,
    }
}
